/**
 * Las marcas de los proveedores de IA, en datos: cada cliente las pinta con lo
 * suyo (el escritorio con `<svg>` de Solid, el teléfono con react-native-svg),
 * pero los trazos y colores salen de aquí y no se copian.
 *
 * Colores de marca en hex, no en tokens: son del dueño de la marca. Un relleno
 * `null` hereda el color del texto (marcas monocromas: un negro fijo se pierde
 * en tema oscuro).
 */

export type AgentMarkId = "claude" | "codex" | "zcode" | "grok" | "gemini" | "opencode";
export type MarkPath = { d: string; fill: string | null };
export type AgentMark = {
  viewBox: string;
  /** Mueve los trazos dentro de la caja. */
  transform?: string;
  paths: MarkPath[];
  /** Los trazos en tema oscuro, si cambian. */
  dark?: MarkPath[];
  /**
   * Solo Gemini: la silueta (`paths`, en un color) recorta manchas de color
   * desenfocadas. `[trazo, color, desenfoque]`.
   */
  spots?: [string, string, number][];
};

/**
 * La marca de un proveedor por su id — el único sitio que decide esto. Antigravity
 * lleva la de Gemini a propósito: su CLI guarda su estado en `~/.gemini/` y sus
 * modelos son Gemini; la marca es de quien corre el turno. Uno desconocido no
 * tiene marca: mejor un hueco que un símbolo que afirme un dueño que no sabemos.
 */
export function agentMarkId(provider: string | null | undefined): AgentMarkId | null {
  if (!provider) return null;
  if (provider === "claude" || provider === "codex" || provider === "zcode" || provider === "grok") return provider;
  if (provider === "antigravity") return "gemini";
  if (provider === "opencode" || provider.startsWith("opencode-")) return "opencode";
  return null;
}

